export function calcMatchRate(recipe, fridgeNames) {
  if (fridgeNames.length === 0) return 0
  const matched = recipe.ingredients.filter((ing) =>
    fridgeNames.some((n) => n.includes(ing.toLowerCase()) || ing.toLowerCase().includes(n)),
  )
  return Math.round((matched.length / recipe.ingredients.length) * 100)
}
